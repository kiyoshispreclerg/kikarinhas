"""Generates src/odysee_emotes.h from Odysee's web front end.

    tools/gen_odysee_emotes.py [emotes.ts stickers.ts] > src/odysee_emotes.h

Without arguments the two files are downloaded from
github.com/OdyseeTeam/odysee-frontend (ui/constants/). Odysee has no API
for these: the site carries the lists itself. Three tables, sorted by name
for a binary search:
  - kk_ody_emotes: Odysee's own emotes, ":name:" in the text, as 48 px PNG;
  - kk_ody_twemoji: ":name:" that stand for a Unicode emoji (the site shows
    Twemoji pictures; we put the character back in the text);
  - kk_ody_stickers: "<stkr>:NAME:<stkr>", PNG, with the price of the paid
    ones in US dollars (0 for the free ones).
"""
import re
import sys
import urllib.request

BASE = "https://raw.githubusercontent.com/OdyseeTeam/odysee-frontend/master/ui/constants/"


def read(arg, name):
    if arg:
        return open(arg, encoding="utf-8").read()
    with urllib.request.urlopen(BASE + name) as r:
        return r.read().decode("utf-8")


emotes_ts = read(sys.argv[1] if len(sys.argv) > 2 else None, "emotes.ts")
stickers_ts = read(sys.argv[2] if len(sys.argv) > 2 else None, "stickers.ts")


def url_path(p):
    # Their list has a few raw spaces in paths.
    return p.replace(" ", "%20")


# getEmotes(px, multiplier): `${px}/Name${multiplier}.png`; the 48 px set is
# getEmotes('48%20px', '%402x').
emotes = {}
for name, path in re.findall(r"buildEmote\('([^']+)',\s*`([^`]+)`\)", emotes_ts):
    path = path.replace("${px}", "48%20px").replace("${multiplier}", "%402x")
    emotes[":%s:" % name] = "https://static.odycdn.com/emoticons/" + url_path(path)

twemoji = {}
for name, _, uni in re.findall(r"buildTwemote\('([^']+)',\s*`([^`]+)`,\s*'([^']*)'\)", emotes_ts):
    if uni:
        twemoji.setdefault(":%s:" % name, uni)

consts = dict(re.findall(r"const (\w+) = '([^']+)';", stickers_ts))
stickers = {}
for name, ref, price in re.findall(r"buildSticker\('([^']+)',\s*(\w+)(?:,\s*([\d.]+))?\)",
                                   stickers_ts):
    if ref in consts:
        stickers[":%s:" % name] = ("https://static.odycdn.com/stickers/" + url_path(consts[ref]),
                                   price or "0")

if not emotes or not twemoji or not stickers:
    sys.exit("gen_odysee_emotes: the lists changed shape (%d emotes, %d twemoji, %d stickers)"
             % (len(emotes), len(twemoji), len(stickers)))


def c_str(s):
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ord(ch) < 0x80:
            out.append(ch)
        else:
            # Octal escapes: a hex escape would swallow the next hex digit.
            out.extend("\\%03o" % b for b in ch.encode("utf-8"))
    return '"' + "".join(out) + '"'


def key(s):
    return s.encode("utf-8")  # strcmp order


print("/* SPDX-License-Identifier: GPL-3.0-or-later */")
print("/* Generated by tools/gen_odysee_emotes.py from odysee-frontend's")
print(" * ui/constants/emotes.ts and stickers.ts (MIT licence, LBRY Inc.).")
print(" * Do not edit by hand. */")
print("#ifndef KK_ODYSEE_EMOTES_H")
print("#define KK_ODYSEE_EMOTES_H")
print()
print("typedef struct {")
print("    const char *name, *value; /* \":name:\"; image URL or the emoji */")
print("    double price;             /* stickers: US dollars, 0 if free */")
print("} kk_ody_named;")
for table, items in (("kk_ody_emotes", {k: (v, "0") for k, v in emotes.items()}),
                     ("kk_ody_twemoji", {k: (v, "0") for k, v in twemoji.items()}),
                     ("kk_ody_stickers", stickers)):
    print()
    print("static const kk_ody_named %s[%d] = {" % (table, len(items)))
    for name in sorted(items, key=key):
        value, price = items[name]
        print("    {%s, %s, %s}," % (c_str(name), c_str(value), price))
    print("};")
print()
print("#endif")
